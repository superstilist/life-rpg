def seed_default_items():
    """Seeds or updates the fantasy shop catalog."""
    for data in DEFAULT_ITEMS:
        item, created = Item.objects.get_or_create(name=data['name'], defaults=data)
        if not created:
            for key, val in data.items():
                setattr(item, key, val)
            item.save()

def generate_random_fantasy_character():
    """Generates 100% random fantasy hero starting at Age 0."""
    race = random.choice(RACES)
    origin_obj = random.choice(ORIGINS)

    prefixes, suffixes = NAME_SYLLABLES.get(race, (['Герой'], ['']))
    name = f"{random.choice(prefixes)}{random.choice(suffixes)}"

    def roll_3d6():
        return sum(random.randint(1, 6) for _ in range(3))

    str_val = roll_3d6() + origin_obj['bonus'].get('strength', 0)
    agi_val = roll_3d6() + origin_obj['bonus'].get('agility', 0)
    int_val = roll_3d6() + origin_obj['bonus'].get('intelligence', 0)
    cha_val = roll_3d6() + origin_obj['bonus'].get('charisma', 0)
    luck_val = roll_3d6() + origin_obj['bonus'].get('luck', 0)

    # Racial stat inclinations
    if race in ['Mountain Dwarf', 'Гірський Дворф']:
        str_val += 3
        agi_val -= 1
    elif race in ['High Elf', 'Вищий Ельф']:
        int_val += 3
        agi_val += 1
    elif race in ['Wild Beastkin', 'Дикий Звіролюд']:
        agi_val += 3
        str_val += 1
    elif race in ['Shadow Tiefling', 'Тіньовий Тіфлінг']:
        cha_val += 3
        int_val += 1
    elif race in ['Dragonborn', 'Дракононароджений']:
        str_val += 2
        cha_val += 2
    else:  # Людина / Human
        str_val += 1
        agi_val += 1
        int_val += 1
        cha_val += 1
        luck_val += 1

    traits = [origin_obj['trait']]
    extra_trait = random.choice(TRAITS_POOL)
    if extra_trait not in traits:
        traits.append(extra_trait)

    starting_gold = random.randint(15, 35) + origin_obj['bonus'].get('gold', 0)
    starting_mana = 25 + origin_obj['bonus'].get('mana', 0)
    starting_hp = 50 + origin_obj['bonus'].get('hp', 0)
    start_loc = origin_obj.get('location', 'Селище Окгем')

    character = Character.objects.create(
        name=name,
        race=race,
        origin=origin_obj['text'],
        traits=traits,
        age=0,
        turns=0,
        hp=starting_hp,
        max_hp=starting_hp,
        mana=starting_mana,
        max_mana=starting_mana,
        gold=starting_gold,
        strength=str_val,
        agility=agi_val,
        intelligence=int_val,
        charisma=cha_val,
        luck=luck_val,
        current_location=start_loc
    )

    LogEntry.objects.create(
        character=character,
        age=0,
        turn=0,
        title="Народження та світанок життя",
        text=f"Немовля раси {race} з'явилося на світ у краї {start_loc}. Передісторія: {origin_obj['text']} Вроджені риси: {', '.join(traits)}. Життєвий шлях розпочався з Року 0!",
        log_type='system'
    )

    seed_default_items()
    starter_potion = Item.objects.filter(name='Мале зілля здоров’я').first()
    if not starter_potion:
        starter_potion = Item.objects.filter(item_type='POTION').first()
    if starter_potion:
        InventoryItem.objects.create(character=character, item=starter_potion, quantity=2)

    return character


