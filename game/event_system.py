def get_active_saga_node(character):
    """Returns the current Main Saga act dictionary if the character has reached its min_age and hasn't completed it."""
    state = character.get_story_state()
    current_act_num = state.get('act', 1)
    for act_data in MAIN_SAGA_ACTS:
        if act_data['act'] == current_act_num:
            return act_data
    return None


def is_saga_ready(character):
    """True if the character is old enough to play the current Main Saga Act."""
    node = get_active_saga_node(character)
    if not node:
        return False
    return character.age >= node['min_age']


def process_saga_choice(character, choice_index):
    """Processes the player's choice in the current Main Saga Act and advances the DB story state to the next Act."""
    node = get_active_saga_node(character)
    if not node:
        return "Всі акти головної саги вже завершено!"
    if character.age < node['min_age']:
        return f"Цей розділ саги відкриється у віці {node['min_age']} років."
    if choice_index < 0 or choice_index >= len(node['choices']):
        return "Некоректний вибір у сазі."

    choice = node['choices'][choice_index]

    cost_gold = choice.get('cost_gold', 0)
    if cost_gold > 0 and character.gold < cost_gold:
        return f"Недостатньо золота для цього рішення! Потрібно {cost_gold}g."

    cost_mana = choice.get('cost_mana', 0)
    if cost_mana > 0 and character.mana < cost_mana:
        return f"Недостатньо мани! Потрібно {cost_mana} MP."

    if cost_gold > 0:
        character.gold -= cost_gold
    if cost_mana > 0:
        character.mana -= cost_mana

    stat_check = choice.get('stat_check')
    is_success = True
    dice_roll = random.randint(1, 20)

    if stat_check:
        char_stat = getattr(character, stat_check, 10)
        luck_mod = character.luck // 4
        total_roll = char_stat + dice_roll + luck_mod
        threshold = choice.get('threshold', 10)

        stat_name_ua = {
            'strength': 'СИЛ',
            'agility': 'СПР',
            'intelligence': 'ІНТ',
            'charisma': 'ХАР',
            'luck': 'УДАЧ'
        }.get(stat_check, stat_check.upper())

        if dice_roll == 20:
            is_success = True
            roll_note = f" [КРИТИЧНИЙ ТРІУМФ 20! Сума: {total_roll} проти {threshold}]"
        elif dice_roll == 1:
            is_success = False
            roll_note = f" [ФАТАЛЬНА ОДИНИЦЯ! Сума: {total_roll} проти {threshold}]"
        else:
            is_success = (total_roll >= threshold)
            roll_note = f" (Кидок d20: {dice_roll} + {stat_name_ua} {char_stat} + УДАЧ {luck_mod} = {total_roll} проти {threshold})"
    else:
        roll_note = ""

    if is_success:
        outcome = choice.get('success_outcome', {})
        msg = choice.get('success_msg', 'Вибір виконано!') + roll_note
    else:
        outcome = choice.get('fail_outcome', choice.get('success_outcome', {}))
        msg = choice.get('fail_msg', choice.get('success_msg', 'Вибір мав непрості наслідки.')) + roll_note

    # Advance turn & age by 1 year for completing a major Saga chapter
    character.turns += 1
    character.age += 1
    if character.age <= 16:
        character.max_hp += 3
        character.max_mana += 2

    character.modify_stats(
        hp=outcome.get('hp', 0),
        mana=outcome.get('mana', 0),
        gold=outcome.get('gold', 0),
        reputation=outcome.get('reputation', 0),
        strength=outcome.get('strength', 0),
        agility=outcome.get('agility', 0),
        intelligence=outcome.get('intelligence', 0),
        charisma=outcome.get('charisma', 0),
        luck=outcome.get('luck', 0),
    )

    # Update persistent DB story state
    state = character.get_story_state()
    completed = state.get('completed_nodes', [])
    completed.append(node['act'])
    state['completed_nodes'] = completed
    state['act'] = node['act'] + 1

    flag_pair = choice.get('flag')
    if flag_pair:
        f_key, f_val = flag_pair
        flags = state.get('flags', {})
        flags[f_key] = f_val
        state['flags'] = flags
        if f_key in ['mentor', 'ending']:
            state[f_key] = f_val

    character.save_story_state(state)

    LogEntry.objects.create(
        character=character,
        age=character.age,
        turn=character.turns,
        title=f"👑 {node['title']}",
        text=msg,
        log_type='system'
    )

    character.check_vitals()
    return msg


