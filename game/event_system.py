INFANCY_EVENTS.extend(_NEW_INFANCY_EVENTS)

ALL_EVENTS = FANTASY_EVENTS + CHILDHOOD_EVENTS + INFANCY_EVENTS

def trigger_random_event(character):
    """Picks a random encounter tailored to the character's life stage."""
    if character.age < 5:
        return random.choice(INFANCY_EVENTS)
    elif character.age < 12:
        return random.choice(CHILDHOOD_EVENTS)
    else:
        return random.choice(FANTASY_EVENTS)

def process_event_choice(character, event_id, choice_index):
    """Processes choice outcome with tabletop d20 roll mechanics and trait synergies."""
    event = next((e for e in ALL_EVENTS if e['id'] == event_id), None)
    if not event or choice_index >= len(event['choices']):
        return "Некоректний вибір у події."

    choice = event['choices'][choice_index]

    # Check costs
    cost_gold = choice.get('cost_gold', 0)
    if cost_gold > 0 and character.gold < cost_gold:
        return f"Недостатньо золота! Потрібно {cost_gold}g."

    cost_mana = choice.get('cost_mana', 0)
    if cost_mana > 0 and character.mana < cost_mana:
        return f"Недостатньо мани! Потрібно {cost_mana} MP."

    if cost_gold > 0:
        character.gold -= cost_gold
    if cost_mana > 0:
        character.mana -= cost_mana

    stat_check = choice.get('stat_check')
    is_success = True
    dice_roll = random.randint(1, 20)

    if stat_check:
        char_stat = getattr(character, stat_check, 10)
        traits = character.traits or []
        trait_bonus = 0
        trait_note = ""

        # Trait synergies (bilingual support)
        if stat_check == 'strength' and any(t in traits for t in ['Giant Blood', 'Кров велетнів', 'Stone Bones', 'Кам’яні кістки', 'Загартований у боях']):
            trait_bonus += 3
            trait_note = " [Риса: +3 СИЛ]"
        elif stat_check == 'agility' and any(t in traits for t in ['Swift Step', 'Швидка хода', 'Eagle Eye', 'Орлине око', 'Інстинкт мисливця', 'Тіньовий крок']):
            trait_bonus += 3
            trait_note = " [Риса: +3 СПР]"
        elif stat_check == 'intelligence' and any(t in traits for t in ['Mana Sensitive', 'Чутливість до мани', 'Спорідненість з розломом', 'Знання трав', 'Рунний зір']):
            trait_bonus += 3
            trait_note = " [Риса: +3 ІНТ]"
        elif stat_check == 'charisma' and any(t in traits for t in ['Silver Tongue', 'Срібний язик', 'Шляхетна кров', 'Благословення сонця']):
            trait_bonus += 3
            trait_note = " [Риса: +3 ХАР]"
        elif stat_check == 'luck' and any(t in traits for t in ['Uncanny Luck', 'Неймовірна вдача', 'Дотик фей', 'Дика удача']):
            trait_bonus += 4
            trait_note = " [Риса: +4 УДАЧ]"

        luck_mod = character.luck // 4
        total_roll = char_stat + dice_roll + luck_mod + trait_bonus
        threshold = choice.get('threshold', 12)

        # Critical checks
        stat_name_ua = {
            'strength': 'СИЛ',
            'agility': 'СПР',
            'intelligence': 'ІНТ',
            'charisma': 'ХАР',
            'luck': 'УДАЧ'
        }.get(stat_check, stat_check.upper())

        if dice_roll == 20:
            is_success = True
            roll_note = f" [КРИТИЧНИЙ УСПІХ 20! Разом: {total_roll} проти складності {threshold}]"
        elif dice_roll == 1:
            is_success = False
            roll_note = f" [КРИТИЧНИЙ ПРОВАЛ 1! Разом: {total_roll} проти складності {threshold}]"
        else:
            is_success = (total_roll >= threshold)
            roll_note = f" (Кидок d20: {dice_roll} + {stat_name_ua} {char_stat} + УДАЧ {luck_mod}{trait_note} = {total_roll} проти складності {threshold})"
    else:
        roll_note = ""

    if is_success:
        outcome = choice.get('success_outcome', {})
        msg = choice.get('success_msg', 'Вибір успішний!') + roll_note
    else:
        outcome = choice.get('fail_outcome', {})
        msg = choice.get('fail_msg', 'Вибір не вдався.') + roll_note

    # Apply outcome effects
    character.modify_stats(
        hp=outcome.get('hp', 0),
        mana=outcome.get('mana', 0),
        gold=outcome.get('gold', 0),
        reputation=outcome.get('reputation', 0),
        strength=outcome.get('strength', 0),
        agility=outcome.get('agility', 0),
        intelligence=outcome.get('intelligence', 0),
        charisma=outcome.get('charisma', 0),
        luck=outcome.get('luck', 0),
    )

    LogEntry.objects.create(
        character=character,
        age=character.age,
        turn=character.turns,
        title=f"Пригода: {event['title']}",
        text=msg,
        log_type='event'
    )

    character.check_vitals()
    return msg


