def get_act_phase(act_id: int, phase_index: int) -> Optional[Dict[str, Any]]:
    """Повертає конкретну фазу наративу для заданого Акту (0..3)."""
    act = get_act_by_id(act_id)
    if not act:
        return None
    phases = act.get("phases", [])
    if 0 <= phase_index < len(phases):
        return phases[phase_index]
    return None


