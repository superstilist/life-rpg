def get_active_novel_state(character) -> Dict[str, Any]:
    """
    Повертає поточний стан проходження новели для персонажа:
    актуальний Акт, поточну фазу (0..max_phase), інтерлюдію або готовність до вибору.
    """
    story_state = character.get_story_state()
    current_act_id = getattr(character, 'story_act', 1) or 1
    completed_acts = story_state.get("completed_acts", [])

    # Перевірка на завершення всіх 8 Актів саги
    if current_act_id > 8 or 8 in completed_acts:
        ending_title = story_state.get('ending') or (
            character.story_flags.get('ending') if isinstance(character.story_flags, dict) else None
        ) or "Спадок Вічності"
        return {
            "act_id": 8,
            "act_data": NOVEL_ACTS[8],
            "current_phase_index": 4,
            "total_phases": 4,
            "max_phase": 4,
            "current_phase": None,
            "revealed_phases": NOVEL_ACTS[8].get("phases", []),
            "is_ready_for_choice": False,
            "choices": [],
            "completed_acts": completed_acts,
            "flags": story_state.get("flags", {}),
            "is_interlude": False,
            "is_story_completed": True,
            "ending": ending_title,
            "years_until_act": 0,
            "interlude_options": [],
        }

    act_data = get_act_by_id(current_act_id) or NOVEL_ACTS.get(1)
    act_id = act_data["act_id"]
    act_age_min = act_data.get("age_min", 0)

    # 4. Перевірка на стан Інтерлюдії: якщо персонаж ще не досяг мінімального віку для Акту
    if character.age < act_age_min:
        years_until_act = act_age_min - character.age
        interlude_intro = get_interlude_intro(character, act_data)
        _band = (
            "тихі роки немовляти" if character.age < 5
            else "роки дитинства" if character.age < 12
            else "роки учнівства" if character.age < 17
            else "роки між битвами"
        )
        interlude_subtitle = f"вік {character.age} · {_band}"
        interlude_options = get_interlude_options(character)
        return {
            "act_id": act_id,
            "act_data": act_data,
            "current_phase_index": 0,
            "total_phases": len(act_data.get("phases", [])),
            "max_phase": len(act_data.get("phases", [])),
            "current_phase": None,
            "revealed_phases": [],
            "is_ready_for_choice": False,
            "choices": [],
            "completed_acts": completed_acts,
            "flags": story_state.get("flags", {}),
            "is_interlude": True,
            "years_until_act": years_until_act,
            "next_act_title": act_data["title"],
            "interlude_intro": interlude_intro,
            "interlude_subtitle": interlude_subtitle,
            "interlude_options": interlude_options,
            "is_story_completed": False,
            "ending": None,
        }

    # Акт активний! Визначаємо поточну фазу (0..total_phases)
    total_phases = len(act_data.get("phases", []))
    current_phase = getattr(character, 'story_phase', 0)
    if current_phase is None:
        current_phase = 0
    current_phase = max(0, min(current_phase, total_phases))

    revealed_phases = []
    for i in range(min(current_phase + 1, total_phases)):
        p = get_act_phase(act_id, i)
        if p:
            revealed_phases.append(p)

    is_ready_for_choice = (current_phase >= total_phases)

    return {
        "act_id": act_id,
        "act_data": act_data,
        "scene_ascii_art": get_act_ascii_art(act_id),
        "current_phase_index": current_phase,
        "total_phases": total_phases,
        "max_phase": total_phases,
        "current_phase": get_act_phase(act_id, current_phase) if not is_ready_for_choice else None,
        "revealed_phases": revealed_phases,
        "is_ready_for_choice": is_ready_for_choice,
        "choices": act_data.get("choices", []) if is_ready_for_choice else [],
        "completed_acts": completed_acts,
        "flags": story_state.get("flags", {}),
        "is_interlude": False,
        "years_until_act": 0,
        "is_story_completed": False,
        "ending": None,
        "interlude_options": [],
    }


def advance_novel_phase(character) -> Dict[str, Any]:
    """
    1. Advance phase: player clicks '▶ Далі' or presses Space/Enter
    -> increments character.story_phase until max phase is reached.
    Зберігає оновлений стан фази безпосередньо в базі даних.
    """
    act_id = getattr(character, 'story_act', 1) or 1
    act_data = get_act_by_id(act_id) or NOVEL_ACTS[1]
    total_phases = len(act_data.get("phases", []))

    current_phase = getattr(character, 'story_phase', 0) or 0
    if current_phase < total_phases:
        character.story_phase = current_phase + 1
        character.save(update_fields=['story_phase', 'updated_at'])
        story_state = character.get_story_state()
        story_state["phase"] = character.story_phase
        story_state["act"] = act_id
        character.save_story_state(story_state)

    return get_active_novel_state(character)


def skip_novel_phases(character) -> Dict[str, Any]:
    """
    2. Skip phase: player clicks '⏭️ До виборів' or presses Tab
    -> sets character.story_phase = max phase, immediately displaying choices.
    Зберігає стан вибору безпосередньо в базі даних.
    """
    act_id = getattr(character, 'story_act', 1) or 1
    act_data = get_act_by_id(act_id) or NOVEL_ACTS[1]
    total_phases = len(act_data.get("phases", []))

    character.story_phase = total_phases
    character.save(update_fields=['story_phase', 'updated_at'])
    story_state = character.get_story_state()
    story_state["phase"] = total_phases
    story_state["act"] = act_id
    character.save_story_state(story_state)

    return get_active_novel_state(character)


