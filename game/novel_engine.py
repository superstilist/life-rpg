def resolve_novel_choice(character, act_id: int, choice_index_or_id: Any) -> Dict[str, Any]:
    """
    3. Resolve choice: player makes choice [1], [2], [3]
    -> applies consequences, logs to Chronicle, records flags,
       advances to next Act or sets next story node!
    """
    act = get_act_by_id(act_id)
    if not act:
        return {"success": False, "message": "Невідомий акт новели."}

    choices = act.get("choices", [])
    choice = None

    if isinstance(choice_index_or_id, int) and 0 <= choice_index_or_id < len(choices):
        choice = choices[choice_index_or_id]
    else:
        # Підтримка клавіатурних номерів вибору '1', '2', '3' (1-based)
        val_str = str(choice_index_or_id).strip()
        if val_str.isdigit():
            idx = int(val_str)
            if 1 <= idx <= len(choices):
                choice = choices[idx - 1]
            elif 0 <= idx < len(choices):
                choice = choices[idx]

        if not choice:
            for c in choices:
                if c.get("id") == val_str:
                    choice = c
                    break

    if not choice:
        return {"success": False, "message": "Невідомий вибір у новелі."}

    stat_check = choice.get("stat_check")
    threshold = choice.get("threshold", 10)
    success = True
    roll_val = 0

    if stat_check:
        char_stat = getattr(character, stat_check, 10)
        d20 = random.randint(1, 20)
        luck_bonus = getattr(character, "luck", 10) // 4
        roll_val = char_stat + d20 + luck_bonus
        success = (d20 == 20) or (roll_val >= threshold)

    cost_gold = choice.get("cost_gold", 0)
    cost_mana = choice.get("cost_mana", 0)

    if character.gold < cost_gold:
        return {"success": False, "message": f"Недостатньо золота (потрібно {cost_gold}g)."}
    if character.mana < cost_mana:
        return {"success": False, "message": f"Недостатньо мани (потрібно {cost_mana} MP)."}

    if cost_gold:
        character.modify_stats(gold=-cost_gold)
    if cost_mana:
        character.modify_stats(mana=-cost_mana)

    outcome = choice.get("success_outcome", {}) if success else choice.get("fail_outcome", {})
    character.modify_stats(**outcome)

    story_flag = choice.get("story_flag")
    story_state = character.get_story_state()
    if not isinstance(character.story_flags, dict):
        character.story_flags = {}
    if story_flag:
        character.story_flags[story_flag] = True
        story_state.setdefault("flags", {})[story_flag] = True

    if "ending_title" in choice:
        character.story_flags["ending"] = choice["ending_title"]
        story_state["ending"] = choice["ending_title"]

    completed = story_state.get("completed_acts", [])
    if act_id not in completed:
        completed.append(act_id)
    story_state["completed_acts"] = completed

    # Перехід до наступного Акту та скидання фази в 0
    next_act_id = act_id + 1
    character.story_act = next_act_id
    character.story_phase = 0
    story_state["act"] = next_act_id
    story_state["phase"] = 0
    character.save_story_state(story_state)

    # Просування віку персонажа та ходів за завершення глави новели
    character.turns += 1
    character.age += 1
    if character.age <= 16:
        character.max_hp += 3
        character.hp = min(character.max_hp, character.hp + 3)
        character.max_mana += 2
        character.mana = min(character.max_mana, character.mana + 2)
    character.save()
    character.check_vitals()

    result_text = choice.get("success_msg", "") if success else choice.get("fail_msg", "")

    # Створюємо запис у Хроніці героя
    from .models import LogEntry
    LogEntry.objects.create(
        character=character,
        age=character.age,
        turn=character.turns,
        title=f"★ {act['title']}: {choice['text']}",
        text=result_text,
        log_type="quest"
    )

    return {
        "success": True,
        "is_check_success": success,
        "roll_value": roll_val,
        "threshold": threshold,
        "message": result_text,
        "act_id": act_id,
        "next_act_id": next_act_id,
        "story_flag": story_flag,
    }


